def calculate_x(a, b):
    """Функція для обчислення значення X залежно від a та b."""
    if a > b:
        return a * b - 1
    elif a == b:
        return 255
    else:  # a < b
        return (a - 5) / b


def build_pyramid(n):
    """Функція для побудови піраміди з цілих чисел від N до 1."""
    for i in range(n, 0, -1):
        # Кількість чисел у поточному рядку (від 1 на вершині до n внизу)
        count = n - i + 1
        # Відступ зліва для вирівнювання по правому краю
        spaces = "  " * (i - 1)
        # Формування рядка з чисел
        numbers = " ".join([str(i)] * count)
        print(spaces + numbers)


def main():
    print(" Частина 1: Обчислення X ")
    try:
        a = float(input("Введіть число a: "))
        b = float(input("Введіть число b: "))

        # Перевірка для варіантів 1-10 (лише додатні числа):
        if a <= 0 or b <= 0:
            print("Помилка: числа a та b повинні бути додатними (більшими за 0).")
        # Якщо ваш варіант 10-20, замініть умову вище на:
        # if not (1 <= a <= 100 and 1 <= b <= 100):
        #     print("Помилка: числа a та b повинні бути в діапазоні від 1 до 100.")
        else:
            x = calculate_x(a, b)
            print(f"Результат обчислення: X = {x}")
    except ValueError:
        print("Помилка: введено некоректні числові дані.")

    print("\n Частина 2: Побудова піраміди ")
    try:
        n = int(input("Введіть ціле число N (від 1 до 10): "))
        if 1 <= n <= 10:
            build_pyramid(n)
        else:
            print("Помилка: число N повинно бути в межах від 1 до 10.")
    except ValueError:
        print("Помилка: необхідно ввести ціле число.")


if __name__ == "__main__":
    main()